#!/bin/sh
# ch25-wifi-blob-boundary —— Wi-Fi blob 符号取证
#
# 章节 25.2 里出现的每一个数字（成员数、导出符号数、未定义符号数、
# ROM 提供数、胶水提供数）都由本脚本产出。脚本只读本机 IDF 与只读
# 归档，不写仓库以外的东西，输出是确定的（排序 + 去重 + 固定顺序）。
#
# 用法：
#   sh tools/symbols.sh              # 打到标准输出
#   sh tools/symbols.sh > inventory.txt
#
# 可覆盖的环境变量：
#   IDF_PATH   （默认 ~/esp/esp-idf）
#   NM         （默认 RISCV_NM，见下）
#   RISCV_NM   （默认 ~/.espressif/tools/riscv32-esp-elf/
#               esp-15.2.0_20251204/riscv32-esp-elf/bin/riscv32-esp-elf-nm）
#
# 依赖：POSIX shell、awk、sort、comm、wc、sed、basename、sha256sum（可选）。
set -eu

# 排序/比较必须与调用者的 locale 无关：comm 要求两侧排序规则一致。
LC_ALL=C
export LC_ALL

IDF_PATH=${IDF_PATH:-$HOME/esp/esp-idf}
RISCV_NM=${RISCV_NM:-$HOME/.espressif/tools/riscv32-esp-elf/esp-15.2.0_20251204/riscv32-esp-elf/bin/riscv32-esp-elf-nm}
NM=${NM:-$RISCV_NM}

LIBDIR="$IDF_PATH/components/esp_wifi/lib/esp32s31"
COEXLIB="$IDF_PATH/components/esp_coex/lib/esp32s31/libcoexist.a"
ROMDIR="$IDF_PATH/components/esp_rom/esp32s31/ld"

TMP=$(mktemp -d "${TMPDIR:-/tmp}/ch25-symbols.XXXXXX")
trap 'rm -rf "$TMP"' EXIT HUP INT TERM

[ -x "$NM" ] || { echo "找不到 nm: $NM" >&2; exit 1; }
[ -d "$LIBDIR" ] || { echo "找不到 $LIBDIR（IDF_PATH 指对了吗？）" >&2; exit 1; }

# 目标库：三个 Wi-Fi blob + coex（对照）。
LIBS=""
for f in libnet80211.a libpp.a libcore.a; do
    LIBS="$LIBS $LIBDIR/$f"
done

# 内部：把一个归档的「已定义符号名」与「未定义符号名」抽成两份排序文件。
# 只取 nm 的第三种格式（name-only 行之外），避免把 "member.o:" 头当符号。
defined_of() { "$NM" --defined-only "$1" 2>/dev/null | awk 'NF==3 {print $3}' | sort -u; }
undefined_of() { "$NM" -u "$1" 2>/dev/null | awk 'NF==2 && $1=="U" {print $2}' | sort -u; }
counts_of() { "$NM" --defined-only "$1" 2>/dev/null | awk 'NF==3 {print $2}' | sort | uniq -c; }

# 每个库的明细
: >"$TMP/u_all"
: >"$TMP/d_all"
for lib in $LIBS; do
    base=$(basename "$lib")
    defined_of "$lib" >"$TMP/d_$base"
    undefined_of "$lib" >"$TMP/u_$base"
    cat "$TMP/u_$base" >>"$TMP/u_all"
    cat "$TMP/d_$base" >>"$TMP/d_all"
done
sort -u -o "$TMP/u_all" "$TMP/u_all"
sort -u -o "$TMP/d_all" "$TMP/d_all"

# ROM 链接脚本提供的符号，两种语法都认：
#   xxx = 0xADDR;                                  （rom.ld / rom.pp.ld …）
#   PROVIDE ( esp_rom_printf = ets_printf );       （rom.api.ld 的别名）
: >"$TMP/rom"
for f in "$ROMDIR"/*.ld; do
    sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\) = 0x[0-9a-fA-F]*;$/\1/p' "$f"
    sed -n 's/^PROVIDE ( *\([A-Za-z_][A-Za-z0-9_]*\) *= *[A-Za-z_][A-Za-z0-9_]* *);$/\1/p' "$f"
done | sort -u >"$TMP/rom"

echo "# ch25 WiFi blob inventory"
echo "# generated by tools/symbols.sh (deterministic: sorted + deduped)"
echo "# idf: $IDF_PATH"
echo "# nm:  $NM"
"$NM" --version 2>/dev/null | head -1 | sed 's/^/# nm-version: /'
echo

echo "## 1. 归档元数据"
for lib in $LIBS "$COEXLIB"; do
    [ -f "$lib" ] || continue
    base=$(basename "$lib")
    size=$(wc -c <"$lib" | tr -d ' ')
    members=$(ar t "$lib" | wc -l | tr -d ' ')
    # nm 对没有符号表的成员会往 stderr 打 "member.o: no symbols"
    stripped=$("$NM" --defined-only "$lib" 2>&1 >/dev/null | grep -c 'no symbols' || true)
    sha=$(sha256sum "$lib" 2>/dev/null | cut -c1-16 || true)
    printf 'lib=%s bytes=%s members=%s stripped_members=%s sha256_16=%s\n' \
        "$base" "$size" "$members" "$stripped" "${sha:-n/a}"
done
echo

echo "## 2. 每个库的已定义符号直方图（nm 类型 → 数量）"
for lib in $LIBS; do
    base=$(basename "$lib")
    printf 'lib=%s defined_total=%s\n' "$base" "$(wc -l <"$TMP/d_$base" | tr -d ' ')"
    counts_of "$lib" | while read -r n t; do
        printf '  %s=%s\n' "$t" "$n"
    done
done
echo

echo "## 3. 未定义符号（U）总数与提供者归属"
u_all=$(wc -l <"$TMP/u_all" | tr -d ' ')
printf 'unique_undefined_all=%s\n' "$u_all"

comm -12 "$TMP/u_all" "$TMP/d_all" >"$TMP/u_self"
comm -12 "$TMP/u_all" "$TMP/rom" >"$TMP/u_rom"

# 其它 S31 预编译归档（espnow/mesh/wapi/smartconfig/phy/coexist/btbb/rftest…）
: >"$TMP/other_def"
find "$IDF_PATH/components" -path '*esp32s31*' -name '*.a' 2>/dev/null | sort | while read -r a; do
    "$NM" --defined-only "$a" 2>/dev/null | awk 'NF==3 {print $3}'
done | sort -u >"$TMP/other_def_tmp"
mv "$TMP/other_def_tmp" "$TMP/other_def"

comm -12 "$TMP/u_all" "$TMP/other_def" >"$TMP/u_other"
cat "$TMP/d_all" "$TMP/rom" "$TMP/other_def" | sort -u >"$TMP/providers"
comm -23 "$TMP/u_all" "$TMP/providers" >"$TMP/u_left"

# 注意：前三类是“重叠计数”（同一个符号可能既在 ROM ld 里、又被别的归档导出），
# 只有最后一行是互斥的剩余集合。
printf 'provided_by_same_set_libs=%s\n' "$(wc -l <"$TMP/u_self" | tr -d ' ')"
printf 'provided_by_rom_linker_scripts=%s\n' "$(wc -l <"$TMP/u_rom" | tr -d ' ')"
printf 'found_in_any_s31_archive_overlapping=%s\n' "$(wc -l <"$TMP/u_other" | tr -d ' ')"
printf 'left_for_idf_c_glue_and_newlib=%s\n' "$(wc -l <"$TMP/u_left" | tr -d ' ')"
echo

echo "## 4. ROM 提供的符号（前 15 个，字典序）"
head -15 "$TMP/u_rom" | sed 's/^/rom: /'
echo

echo "## 5. 胶水层要补的符号（ROM + 其它归档都不提供的全部，字典序）"
sed 's/^/glue: /' "$TMP/u_left"
echo

echo "## 6. 未定义符号的形态分类（按库）"
for lib in $LIBS; do
    base=$(basename "$lib")
    f="$TMP/u_$base"
    printf 'lib=%s unique=%s\n' "$base" "$(wc -l <"$f" | tr -d ' ')"
    printf '  ieee80211_*=%s\n' "$(grep -c '^ieee80211_' "$f" || true)"
    printf '  hal_*=%s\n' "$(grep -c '^hal_' "$f" || true)"
    printf '  pm_*=%s\n' "$(grep -c '^pm_' "$f" || true)"
    printf '  pp_*=%s\n' "$(grep -c '^pp_' "$f" || true)"
    printf '  g_globals=%s\n' "$(grep -c '^g_' "$f" || true)"
    printf '  compiler_rt(__*)=%s\n' "$(grep -c '^__' "$f" || true)"
    printf '  libc_candidates=%s\n' "$(grep -cE '^(mem|str)[a-z]+$' "$f" || true)"
done
echo

echo "## 7. OS 抽象指针（ROM 数据符号，blob 经它拿到调用方能力表）"
grep -n 'g_osi_funcs_p' "$ROMDIR"/*.ld | sed 's|'"$ROMDIR"'/|rom-ld:|'
echo

echo "## 8. blob 自己导出的公共入口（前 20 个 esp_wifi_*/esp_* ，字典序）"
for lib in $LIBS; do
    base=$(basename "$lib")
    "$NM" --defined-only "$lib" 2>/dev/null | awk 'NF==3 && $2=="T" {print $3}' |
        grep -E '^esp_(wifi|netif|coex|event|now)' | sort -u |
        sed "s|^|$base: |"
done | head -20
echo

echo "## 9. coex 归档（对照）"
if [ -f "$COEXLIB" ]; then
    printf 'libcoexist.a defined_total=%s\n' "$(defined_of "$COEXLIB" | wc -l | tr -d ' ')"
    printf 'libcoexist.a unique_undefined=%s\n' "$(undefined_of "$COEXLIB" | wc -l | tr -d ' ')"
    defined_of "$COEXLIB" | grep -E '^esp_coex' | head -10 | sed 's/^/coex: /'
fi
