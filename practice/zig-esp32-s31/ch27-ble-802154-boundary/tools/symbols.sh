#!/bin/sh
# ch27-ble-802154-boundary —— BLE / 802.15.4 符号取证
#
# 章节 27.2 里出现的每一个数字（归档字节数、成员数、已定义/未定义符号数、
# 归属拆分、glue 列表、ROM 里有什么/没有什么、802.15.4 源码规模）都由本
# 脚本产出。脚本只读本机 IDF 与只读归档，不写仓库以外的东西；输出是确定的
# （LC_ALL=C + 排序 + 去重 + 固定顺序）。
#
# 用法：
#   sh tools/symbols.sh              # 打到标准输出
#   sh tools/symbols.sh > inventory.txt
#
# 可覆盖的环境变量：
#   IDF_PATH   （默认 ~/esp/esp-idf）
#   NM         （默认 RISCV_NM，见下）
#   RISCV_NM   （默认 ~/.espressif/tools/riscv32-esp-elf/
#               esp-15.2.0_20251204/riscv32-esp-elf/bin/riscv32-esp-elf-nm）
#
# 依赖：POSIX shell、awk、sort、comm、wc、sed、basename、sha256sum（可选）。
#
# 只落摘要：不要把 `nm` 的完整转储写进仓库（几百 KB，code-site 会当死链）。
set -eu

LC_ALL=C
export LC_ALL

IDF_PATH=${IDF_PATH:-$HOME/esp/esp-idf}
RISCV_NM=${RISCV_NM:-$HOME/.espressif/tools/riscv32-esp-elf/esp-15.2.0_20251204/riscv32-esp-elf/bin/riscv32-esp-elf-nm}
NM=${NM:-$RISCV_NM}

BTDIR="$IDF_PATH/components/bt/controller/lib_esp32s31/esp32s31-bt-lib"
PHYDIR="$IDF_PATH/components/esp_phy/lib/esp32s31"
OTLIB="$IDF_PATH/components/openthread/lib/esp32s31/libopenthread_br.a"
I154DIR="$IDF_PATH/components/ieee802154"
I154LL="$IDF_PATH/components/esp_hal_ieee802154/esp32s31/include/hal/ieee802154_ll.h"
I154API="$IDF_PATH/components/ieee802154/include/esp_ieee802154.h"
COEX154="$IDF_PATH/components/esp_coex/include/esp_coex_i154.h"
ROMDIR="$IDF_PATH/components/esp_rom/esp32s31/ld"

TMP=$(mktemp -d "${TMPDIR:-/tmp}/ch27-symbols.XXXXXX")
trap 'rm -rf "$TMP"' EXIT HUP INT TERM

[ -x "$NM" ] || { echo "找不到 nm: $NM" >&2; exit 1; }
[ -d "$BTDIR" ] || { echo "找不到 $BTDIR（IDF_PATH 指对了吗？）" >&2; exit 1; }

# 五个 S31 BT 归档：三块 controller（BLE / BR-EDR / 公共）+ 基带 + 测试模式。
BLES="libble_app.a libbtdm_common.a libbredr_app.a"
BB="libbtbb.a libbttestmode.a"
LIBS=""
for f in $BLES; do LIBS="$LIBS $BTDIR/$f"; done
for f in $BB; do LIBS="$LIBS $PHYDIR/$f"; done

defined_of() { "$NM" --defined-only "$1" 2>/dev/null | awk 'NF==3 {print $3}' | sort -u; }
undefined_of() { "$NM" -u "$1" 2>/dev/null | awk 'NF==2 && $1=="U" {print $2}' | sort -u; }
counts_of() { "$NM" --defined-only "$1" 2>/dev/null | awk 'NF==3 {print $2}' | sort | uniq -c; }

# 每个库的符号集合
: >"$TMP/all_defined"
: >"$TMP/all_undef"
for lib in $LIBS; do
    base=$(basename "$lib")
    defined_of "$lib" >"$TMP/d_$base"
    undefined_of "$lib" >"$TMP/u_$base"
    cat "$TMP/d_$base" >>"$TMP/all_defined"
    cat "$TMP/u_$base" >>"$TMP/all_undef"
done
sort -u -o "$TMP/all_defined" "$TMP/all_defined"
sort -u -o "$TMP/all_undef" "$TMP/all_undef"

# ROM 链接脚本（掩膜 ROM）提供的符号，两种语法都认。
: >"$TMP/rom"
for f in "$ROMDIR"/*.ld; do
    sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\) = 0x[0-9a-fA-F]*;$/\1/p' "$f"
    sed -n 's/^PROVIDE ( *\([A-Za-z_][A-Za-z0-9_]*\) *= *[A-Za-z_][A-Za-z0-9_]* *);$/\1/p' "$f"
done | sort -u >"$TMP/rom"

echo "# ch27 BLE / 802.15.4 inventory"
echo "# generated by tools/symbols.sh (deterministic: LC_ALL=C + sorted + deduped)"
echo "# idf: $IDF_PATH"
echo "# nm:  $NM"
"$NM" --version 2>/dev/null | head -1 | sed 's/^/# nm-version: /'
echo

echo "## 1. 归档元数据（S31）"
for lib in $LIBS "$OTLIB"; do
    [ -f "$lib" ] || continue
    base=$(basename "$lib")
    size=$(wc -c <"$lib" | tr -d ' ')
    members=$(ar t "$lib" | wc -l | tr -d ' ')
    stripped=$("$NM" --defined-only "$lib" 2>&1 >/dev/null | grep -c 'no symbols' || true)
    sha=$(sha256sum "$lib" 2>/dev/null | cut -c1-16 || true)
    printf 'lib=%s bytes=%s members=%s stripped_members=%s sha256_16=%s\n' \
        "$base" "$size" "$members" "$stripped" "${sha:-n/a}"
done
echo

echo "## 2. 每库已定义符号直方图（nm 类型 → 数量）与未定义（U）总数"
for lib in $LIBS; do
    base=$(basename "$lib")
    printf 'lib=%s defined_total=%s unique_undefined=%s\n' \
        "$base" "$(wc -l <"$TMP/d_$base" | tr -d ' ')" \
        "$(wc -l <"$TMP/u_$base" | tr -d ' ')"
    counts_of "$lib" | while read -r n t; do
        printf '  %s=%s\n' "$t" "$n"
    done
done
echo

echo "## 3. libble_app.a 未定义符号的归属（互斥拆分）"
comm -12 "$TMP/u_libble_app.a" "$TMP/all_defined" >"$TMP/ble_self"
comm -12 "$TMP/u_libble_app.a" "$TMP/rom" >"$TMP/ble_rom"
cat "$TMP/all_defined" "$TMP/rom" | sort -u >"$TMP/ble_providers"
comm -23 "$TMP/u_libble_app.a" "$TMP/ble_providers" >"$TMP/ble_left"
printf 'unique_undefined=%s\n' "$(wc -l <"$TMP/u_libble_app.a" | tr -d ' ')"
printf 'provided_by_the_five_s31_bt_archives=%s\n' "$(wc -l <"$TMP/ble_self" | tr -d ' ')"
printf 'provided_by_rom_linker_scripts=%s\n' "$(wc -l <"$TMP/ble_rom" | tr -d ' ')"
printf 'left_for_linker_and_newlib=%s\n' "$(wc -l <"$TMP/ble_left" | tr -d ' ')"
echo

echo "## 4. 上面剩下的符号（全部，字典序）——这就是 BLE 对外的真实 ABI 缝"
sed 's/^/glue: /' "$TMP/ble_left"
echo

echo "## 5. libble_app.a 内部的 r_* 前缀（重入/关中断变体）"
printf 'defined_r_prefix=%s\n' "$(grep -c '^r_' "$TMP/d_libble_app.a" || true)"
printf 'undefined_r_prefix=%s\n' "$(grep -c '^r_' "$TMP/u_libble_app.a" || true)"
echo

echo "## 6. libbtdm_common.a 的未定义归属"
comm -12 "$TMP/u_libbtdm_common.a" "$TMP/ble_providers" >"$TMP/common_self"
comm -23 "$TMP/u_libbtdm_common.a" "$TMP/ble_providers" >"$TMP/common_left"
printf 'unique_undefined=%s provided_by_ble_set_plus_rom=%s left=%s\n' \
    "$(wc -l <"$TMP/u_libbtdm_common.a" | tr -d ' ')" \
    "$(wc -l <"$TMP/common_self" | tr -d ' ')" \
    "$(wc -l <"$TMP/common_left" | tr -d ' ')"
sed 's/^/glue: /' "$TMP/common_left"
echo

echo "## 7. ROM 链接脚本里与 BT/PHY 有关的符号（否定证据：没有 controller 符号）"
printf 'rom_r_ble_or_r_btdm_count=%s\n' \
    "$(grep -cE '^(r_ble|r_btdm)' "$TMP/rom" || true)"
printf 'rom_phy_bt_count=%s\n' "$(grep -c '^phy_bt' "$TMP/rom" || true)"
printf 'rom_coex_bt_count=%s\n' "$(grep -c '^coex_bt' "$TMP/rom" || true)"
grep -E '^(phy_bt|coex_bt)' "$TMP/rom" | head -14 | sed 's/^/rom: /'
echo

echo "## 8. 802.15.4 侧：没有归档，只有源码（所以本章不“链接 blob”）"
printf 'archives_named_802154_in_idf=%s\n' \
    "$(find "$IDF_PATH/components" -path '*esp32s31*' -name '*.a' 2>/dev/null | grep -c 802154 || true)"
printf 'driver_files=%s\n' "$(ls "$I154DIR"/driver/*.c "$I154DIR"/esp_ieee802154.c 2>/dev/null | wc -l | tr -d ' ')"
printf 'driver_lines=%s\n' "$(cat "$I154DIR"/driver/*.c "$I154DIR"/esp_ieee802154.c 2>/dev/null | wc -l | tr -d ' ')"
printf 'driver_frame_lines=%s\n' "$(wc -l <"$I154DIR/driver/esp_ieee802154_frame.c" 2>/dev/null | tr -d ' ')"
printf 'll_static_inline=%s\n' "$(grep -c 'static inline' "$I154LL" 2>/dev/null || true)"
printf 'public_api_functions=%s\n' \
    "$(grep -cE '^(esp_err_t|void|int|bool|uint[0-9]+_t|esp_ieee802154_[a-z_]+_t|int8_t|uint8_t) +esp_ieee802154_[a-z_0-9]+' "$I154API" 2>/dev/null || true)"
printf 'coex_i154_functions=%s\n' "$(grep -c 'esp_coex_ieee802154' "$COEX154" 2>/dev/null || true)"
echo

echo "## 9. BT controller 的链接脚本片段（数据段被 SURROUND，用于 memcpy 出 ROM 初值）"
grep -n 'bt_bss -> dram0_bss\|data -> dram0_data\|archive: libbtdm_common.a' \
    "$IDF_PATH/components/bt/controller/linker_esp_btdm_controller.lf" 2>/dev/null |
    sed 's|'"$IDF_PATH"'/components/bt/controller/|lf:|' | head -8
echo

echo "## 10. OpenThread border-router 归档（Thread 的“边界”，本章只统计不链接）"
if [ -f "$OTLIB" ]; then
    printf 'libopenthread_br.a defined=%s unique_undefined=%s\n' \
        "$(defined_of "$OTLIB" | wc -l | tr -d ' ')" \
        "$(undefined_of "$OTLIB" | wc -l | tr -d ' ')"
    defined_of "$OTLIB" | grep -E '^ot' | head -8 | sed 's/^/ot: /'
fi
